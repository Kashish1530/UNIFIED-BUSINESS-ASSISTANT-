"""
Northwind SQLite → Neon PostgreSQL Migration Script
====================================================
Reads NEONDB_URL from the environment (or .env file).
Never prints, logs, or exposes credentials.

Usage
-----
    python scripts/migrate_to_postgres.py            # migrate
    python scripts/migrate_to_postgres.py --dry-run  # print DDL only, no DB contact

Safety guarantees
-----------------
- SQLite database is opened read-only; never modified.
- All PostgreSQL changes run inside a single transaction; rolled back on error.
- Script is idempotent: DROP … CASCADE before re-creating tables.
- Sequences are set to MAX(pk) after bulk insert, never to sqlite_sequence values.
- No credentials are printed or logged at any verbosity level.
"""

import argparse
import os
import sqlite3
import sys
from pathlib import Path

# ---------------------------------------------------------------------------
# Table definitions in FK-dependency order (parents before children).
# ---------------------------------------------------------------------------

# CREATE TABLE statements use GENERATED BY DEFAULT AS IDENTITY so that explicit
# integer IDs from SQLite can be inserted, then the sequence is corrected after.
POSTGRES_DDL: list[tuple[str, str]] = [
    (
        "categories",
        """
        CREATE TABLE categories (
            categoryid   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            categoryname VARCHAR(50),
            description  VARCHAR(255)
        )
        """,
    ),
    (
        "customers",
        """
        CREATE TABLE customers (
            customerid   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            customername VARCHAR(50),
            contactname  VARCHAR(50),
            address      VARCHAR(50),
            city         VARCHAR(20),
            postalcode   VARCHAR(10),
            country      VARCHAR(15)
        )
        """,
    ),
    (
        "employees",
        """
        CREATE TABLE employees (
            employeeid  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            lastname    VARCHAR(15),
            firstname   VARCHAR(15),
            birthdate   TIMESTAMP,
            photo       VARCHAR(25),
            notes       VARCHAR(1024)
        )
        """,
    ),
    (
        "shippers",
        """
        CREATE TABLE shippers (
            shipperid   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            shippername VARCHAR(25),
            phone       VARCHAR(15)
        )
        """,
    ),
    (
        "suppliers",
        """
        CREATE TABLE suppliers (
            supplierid   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            suppliername VARCHAR(50),
            contactname  VARCHAR(50),
            address      VARCHAR(50),
            city         VARCHAR(20),
            postalcode   VARCHAR(10),
            country      VARCHAR(15),
            phone        VARCHAR(15)
        )
        """,
    ),
    (
        "products",
        """
        CREATE TABLE products (
            productid   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            productname VARCHAR(50),
            supplierid  INTEGER REFERENCES suppliers(supplierid),
            categoryid  INTEGER REFERENCES categories(categoryid),
            unit        VARCHAR(25),
            price       NUMERIC(10, 2)
        )
        """,
    ),
    (
        "orders",
        """
        CREATE TABLE orders (
            orderid    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            customerid INTEGER REFERENCES customers(customerid),
            employeeid INTEGER REFERENCES employees(employeeid),
            orderdate  TIMESTAMP,
            shipperid  INTEGER REFERENCES shippers(shipperid)
        )
        """,
    ),
    (
        "orderdetails",
        """
        CREATE TABLE orderdetails (
            orderdetailid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            orderid       INTEGER REFERENCES orders(orderid),
            productid     INTEGER REFERENCES products(productid),
            quantity      INTEGER
        )
        """,
    ),
]

# SQLite table name → (postgres table name, postgres column names in order)
# Column names are lowercased to match PostgreSQL's unquoted identifier folding.
SQLITE_TO_PG: dict[str, tuple[str, list[str]]] = {
    "Categories":   ("categories",   ["categoryid", "categoryname", "description"]),
    "Customers":    ("customers",    ["customerid", "customername", "contactname", "address", "city", "postalcode", "country"]),
    "Employees":    ("employees",    ["employeeid", "lastname", "firstname", "birthdate", "photo", "notes"]),
    "Shippers":     ("shippers",     ["shipperid", "shippername", "phone"]),
    "Suppliers":    ("suppliers",    ["supplierid", "suppliername", "contactname", "address", "city", "postalcode", "country", "phone"]),
    "Products":     ("products",     ["productid", "productname", "supplierid", "categoryid", "unit", "price"]),
    "Orders":       ("orders",       ["orderid", "customerid", "employeeid", "orderdate", "shipperid"]),
    "OrderDetails": ("orderdetails", ["orderdetailid", "orderid", "productid", "quantity"]),
}

# FK-dependency order for DROP (reverse of creation order)
DROP_ORDER = [
    "orderdetails", "orders", "products",
    "suppliers", "shippers", "employees", "customers", "categories",
]

# Expected row counts (from verified SQLite database)
EXPECTED_COUNTS: dict[str, int] = {
    "categories":   8,
    "customers":    91,
    "employees":    10,
    "shippers":     3,
    "suppliers":    29,
    "products":     77,
    "orders":       196,
    "orderdetails": 518,
}


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def get_project_root() -> Path:
    """Resolve project root relative to this script's location."""
    return Path(__file__).resolve().parent.parent


def load_env_file(env_path: Path | None = None) -> None:
    """Load key=value pairs from .env into os.environ (non-overwriting)."""
    target = env_path or (get_project_root() / ".env")
    if not target.exists():
        return
    with open(target, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            key, val = line.split("=", 1)
            key = key.strip()
            val = val.strip().strip("\"'")
            if key and key not in os.environ:
                os.environ[key] = val


def get_neon_url() -> str:
    """
    Return NEONDB_URL from environment. Raises if absent or empty.
    Never prints or logs the URL.
    """
    url = os.environ.get("NEONDB_URL", "").strip()
    if not url:
        raise RuntimeError(
            "NEONDB_URL is not set. Add it to .env or set it as an environment variable.\n"
            "Format: postgresql://user:password@host/dbname?sslmode=require"
        )
    return url


def open_sqlite_readonly(db_path: Path) -> sqlite3.Connection:
    """Open Northwind SQLite database in read-only URI mode."""
    if not db_path.exists():
        raise FileNotFoundError(f"SQLite database not found: {db_path}")
    uri = f"{db_path.as_uri()}?mode=ro"
    conn = sqlite3.connect(uri, uri=True)
    conn.row_factory = sqlite3.Row
    return conn


def fetch_sqlite_table(sqlite_conn: sqlite3.Connection, table: str) -> list[sqlite3.Row]:
    """Fetch all rows from a SQLite table."""
    return sqlite_conn.execute(f'SELECT * FROM "{table}"').fetchall()


def build_insert_sql(pg_table: str, columns: list[str]) -> str:
    """Build a parameterised INSERT statement for psycopg2."""
    col_list = ", ".join(columns)
    placeholders = ", ".join(f"%s" for _ in columns)
    return f"INSERT INTO {pg_table} ({col_list}) VALUES ({placeholders})"


def reset_sequence(pg_cursor, pg_table: str, pk_col: str) -> None:
    """
    Set the identity sequence to MAX(pk_col) so future INSERTs
    do not collide with explicitly inserted IDs.
    Uses MAX() — safe even for non-contiguous IDs (e.g. Orders starting at 10248).
    """
    pg_cursor.execute(
        f"SELECT SETVAL(pg_get_serial_sequence('{pg_table}', '{pk_col}'), "
        f"COALESCE(MAX({pk_col}), 1)) FROM {pg_table}"
    )


# ---------------------------------------------------------------------------
# Core migration
# ---------------------------------------------------------------------------

def run_migration(dry_run: bool = False, overwrite: bool = False) -> None:
    """
    Execute the full migration inside a single PostgreSQL transaction.
    Rolls back automatically if any step fails.
    """
    # --- Dry run: just print DDL ---
    if dry_run:
        print("=== DRY RUN: PostgreSQL DDL (no database will be contacted) ===\n")
        for pg_table, ddl in POSTGRES_DDL:
            print(f"-- {pg_table}")
            print(ddl.strip())
            print()
        print("=== DROP ORDER (reverse FK) ===")
        for t in DROP_ORDER:
            print(f"  DROP TABLE IF EXISTS {t} CASCADE;")
        return

    if not overwrite:
        print(
            "Refusing to drop or replace tables without --overwrite.\n"
            "Pass --overwrite to proceed with migration and recreate the schema.",
            file=sys.stderr,
        )
        sys.exit(1)

    load_env_file()
    project_root = get_project_root()
    sqlite_path = project_root / "data" / "northwind.db"

    # Import psycopg2 here so dry-run works without it installed
    try:
        import psycopg2
    except ImportError:
        print(
            "ERROR: psycopg2-binary is not installed.\n"
            "Run: pip install psycopg2-binary",
            file=sys.stderr,
        )
        sys.exit(1)

    neon_url = get_neon_url()

    print("Opening SQLite database (read-only)...")
    sqlite_conn = open_sqlite_readonly(sqlite_path)

    pg_conn = None
    pg_cur = None

    try:
        print("Connecting to Neon PostgreSQL...")
        # Connection string is never printed
        pg_conn = psycopg2.connect(neon_url)
        pg_conn.autocommit = False  # explicit transaction
        pg_cur = pg_conn.cursor()
        # ----------------------------------------------------------------
        # Step 1: Drop existing tables in reverse FK order (idempotent)
        # ----------------------------------------------------------------
        print("\n[1/5] Dropping existing tables (if any)...")
        for tbl in DROP_ORDER:
            pg_cur.execute(f"DROP TABLE IF EXISTS {tbl} CASCADE")
            print(f"      Dropped: {tbl}")

        # ----------------------------------------------------------------
        # Step 2: Create tables in FK-dependency order
        # ----------------------------------------------------------------
        print("\n[2/5] Creating tables...")
        for pg_table, ddl in POSTGRES_DDL:
            pg_cur.execute(ddl)
            print(f"      Created: {pg_table}")

        # ----------------------------------------------------------------
        # Step 3: Bulk-insert data from SQLite (FK dependency order)
        # ----------------------------------------------------------------
        print("\n[3/5] Inserting data...")
        inserted: dict[str, int] = {}

        for sqlite_table, (pg_table, columns) in SQLITE_TO_PG.items():
            rows = fetch_sqlite_table(sqlite_conn, sqlite_table)
            if not rows:
                print(f"      {pg_table:15s}: 0 rows (source empty)")
                inserted[pg_table] = 0
                continue

            sql = build_insert_sql(pg_table, columns)
            # sqlite3.Row objects unpack to tuples in column-definition order
            pg_rows = [tuple(row) for row in rows]

            pg_cur.executemany(sql, pg_rows)
            inserted[pg_table] = len(rows)
            print(f"      {pg_table:15s}: {len(rows):>4} rows inserted")

        # ----------------------------------------------------------------
        # Step 4: Reset identity sequences to MAX(pk)
        # ----------------------------------------------------------------
        print("\n[4/5] Resetting identity sequences...")
        pk_map = {
            "categories":   "categoryid",
            "customers":    "customerid",
            "employees":    "employeeid",
            "shippers":     "shipperid",
            "suppliers":    "supplierid",
            "products":     "productid",
            "orders":       "orderid",
            "orderdetails": "orderdetailid",
        }
        for tbl, pk in pk_map.items():
            reset_sequence(pg_cur, tbl, pk)
            print(f"      Sequence reset: {tbl}.{pk}")

        # ----------------------------------------------------------------
        # Step 5: Verify row counts before committing
        # ----------------------------------------------------------------
        print("\n[5/5] Verifying row counts...")
        all_ok = True
        for pg_table, expected in EXPECTED_COUNTS.items():
            pg_cur.execute(f"SELECT COUNT(*) FROM {pg_table}")
            actual = pg_cur.fetchone()[0]
            status = "OK" if actual == expected else "MISMATCH"
            if actual != expected:
                all_ok = False
            print(f"      {pg_table:15s}: {actual:>4} rows  (expected {expected:>4})  [{status}]")

        if not all_ok:
            raise RuntimeError("Row count verification failed. Transaction rolled back.")

        # ----------------------------------------------------------------
        # Commit
        # ----------------------------------------------------------------
        pg_conn.commit()
        print("\n[OK] Migration committed successfully.")
        print(f"  Total rows migrated: {sum(EXPECTED_COUNTS.values())}")

    except Exception as exc:
        if pg_conn is not None:
            pg_conn.rollback()
        print(f"\n[FAIL] Migration FAILED - transaction rolled back.", file=sys.stderr)
        # Print the error class and message but never the connection string
        print(f"  Error: {type(exc).__name__}: {exc}", file=sys.stderr)
        sys.exit(1)

    finally:
        sqlite_conn.close()
        if pg_cur is not None:
            pg_cur.close()
        if pg_conn is not None:
            pg_conn.close()

# ---------------------------------------------------------------------------
# Entry point
# ---------------------------------------------------------------------------

def main() -> None:
    parser = argparse.ArgumentParser(
        description="Migrate Northwind data from SQLite to Neon PostgreSQL."
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Print the PostgreSQL DDL without connecting to any database.",
    )
    parser.add_argument(
        "--overwrite",
        action="store_true",
        help="Allow dropping and recreating existing tables in Neon PostgreSQL.",
    )
    args = parser.parse_args()
    run_migration(dry_run=args.dry_run, overwrite=args.overwrite)


if __name__ == "__main__":
    main()
