class EnvLoadingTests(unittest.TestCase):

    def test_21_load_env_file_sets_variables(self):
        """load_env_file must parse key=value pairs into os.environ."""
        import tempfile
        with tempfile.NamedTemporaryFile(mode="w", suffix=".env", delete=False) as f:
            f.write("# comment\n")
            f.write("TEST_NEON_KEY=testvalue123\n")
            f.write("ANOTHER_KEY='quoted'\n")
            tmp = Path(f.name)
        try:
            with patch.dict("os.environ", {}, clear=False):
                os.environ.pop("TEST_NEON_KEY", None)
                os.environ.pop("ANOTHER_KEY", None)
                load_env_file(tmp)
                self.assertEqual(os.environ.get("TEST_NEON_KEY"), "testvalue123")
                self.assertEqual(os.environ.get("ANOTHER_KEY"), "quoted")
        finally:
            tmp.unlink()

    def test_22_load_env_does_not_overwrite_existing(self):
        """load_env_file must not overwrite variables already in os.environ."""
        import tempfile
        with tempfile.NamedTemporaryFile(mode="w", suffix=".env", delete=False) as f:
            f.write("PREEXISTING_KEY=file_value\n")
            tmp = Path(f.name)
        try:
            with patch.dict("os.environ", {"PREEXISTING_KEY": "original"}, clear=False):
                load_env_file(tmp)
                self.assertEqual(os.environ.get("PREEXISTING_KEY"), "original")
        finally:
            tmp.unlink()

    def test_23_get_neon_url_raises_when_absent(self):
        """get_neon_url must raise RuntimeError when NEONDB_URL is not set."""
        with patch.dict("os.environ", {}, clear=True):
            with self.assertRaises(RuntimeError) as ctx:
                get_neon_url()
            self.assertIn("NEONDB_URL", str(ctx.exception))

    def test_24_load_env_file_missing_file_is_silent(self):
        """load_env_file must not raise if .env file does not exist."""
        try:
            load_env_file(Path("/nonexistent/.env_that_does_not_exist"))
        except Exception as e:
            self.fail(f"load_env_file raised unexpectedly: {e}")


