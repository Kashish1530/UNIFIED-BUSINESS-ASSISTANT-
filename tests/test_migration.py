def _make_pg_mock(row_counts: dict[str, int] | None = None):
    """
    Build a psycopg2 mock that returns configurable COUNT(*) results.
    cursor.fetchone() returns (count,) in order of EXPECTED_COUNTS keys.
    """
    counts = row_counts or EXPECTED_COUNTS
    cur = MagicMock()

    # Sequence of fetchone() results: one per table count + FK checks + seq checks
    count_results = [(n,) for n in counts.values()]
    fk_results    = [(r,) for _, _, r in FK_CHECKS]
    seq_results   = [(v,) for _, _, v in [
        ("categories",   "categoryid",   8),
        ("customers",    "customerid",   91),
        ("employees",    "employeeid",   10),
        ("shippers",     "shipperid",    3),
        ("suppliers",    "supplierid",   29),
        ("products",     "productid",    77),
        ("orders",       "orderid",      10443),
        ("orderdetails", "orderdetailid", 518),
    ]]
    cur.fetchone.side_effect = count_results + fk_results + seq_results

    conn = MagicMock()
    conn.cursor.return_value = cur
    conn.__enter__ = MagicMock(return_value=conn)
    conn.__exit__ = MagicMock(return_value=False)
    return conn, cur


