class VerificationScriptTests(unittest.TestCase):

    def _build_verification_mock(self, counts: dict[str, int] | None = None, seq_override=None):
        """Build a psycopg2 mock that returns given counts for verification."""
        effective = counts or VERIFY_EXPECTED_COUNTS
        pg_cur = MagicMock()
        # Row counts (8) + FK join checks (4) + sequence checks (8 * (max_pk, (schemaname, sequencename, increment_by), (last_val, is_called)))
        count_side = [(v,) for v in effective.values()]
        fk_side    = [(r,) for _, _, r in FK_CHECKS]
        if seq_override is not None:
            seq_side = seq_override
        else:
            seq_side = []
            for tbl, pk, min_val in SEQUENCE_CHECKS:
                # 1st fetchone: max_pk
                seq_side.append((min_val,))
                # 2nd fetchone: (schemaname, sequencename, increment_by)
                seq_side.append(("public", f"{tbl}_{pk}_seq", 1))
                # 3rd fetchone: (last_value, is_called) from sequence relation
                seq_side.append((min_val, True))

        pg_cur.fetchone.side_effect = count_side + fk_side + seq_side
        pg_conn = MagicMock()
        pg_conn.cursor.return_value = pg_cur
        return pg_conn

