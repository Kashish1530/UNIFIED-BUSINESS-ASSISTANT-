class MigrationDDLTests(unittest.TestCase):

    def test_01_all_eight_tables_in_ddl(self):
        """POSTGRES_DDL must contain exactly 8 table entries."""
        names = [name for name, _ in POSTGRES_DDL]
        self.assertEqual(len(names), 8)
        expected = {
            "categories", "customers", "employees", "shippers",
            "suppliers", "products", "orders", "orderdetails",
        }
        self.assertEqual(set(names), expected)

    def test_02_ddl_creation_order_respects_fk_dependencies(self):
        """Parent tables must appear before child tables in POSTGRES_DDL."""
        names = [name for name, _ in POSTGRES_DDL]
        # categories and suppliers must precede products
        self.assertLess(names.index("categories"), names.index("products"))
        self.assertLess(names.index("suppliers"),  names.index("products"))
        # customers, employees, shippers must precede orders
        self.assertLess(names.index("customers"),  names.index("orders"))
        self.assertLess(names.index("employees"),  names.index("orders"))
        self.assertLess(names.index("shippers"),   names.index("orders"))
        # orders and products must precede orderdetails
        self.assertLess(names.index("orders"),     names.index("orderdetails"))
        self.assertLess(names.index("products"),   names.index("orderdetails"))

    def test_03_drop_order_is_reverse_of_creation_order(self):
        """DROP_ORDER must be the strict reverse of POSTGRES_DDL table order."""
        creation_names = [name for name, _ in POSTGRES_DDL]
        self.assertEqual(DROP_ORDER, list(reversed(creation_names)))

    def test_04_ddl_uses_identity_not_serial(self):
        """All PKs must use GENERATED BY DEFAULT AS IDENTITY, not SERIAL."""
        for name, ddl in POSTGRES_DDL:
            self.assertIn("GENERATED BY DEFAULT AS IDENTITY", ddl, msg=f"Table: {name}")
            self.assertNotIn("SERIAL", ddl.upper(), msg=f"Table: {name}")

    def test_05_ddl_contains_no_autoincrement(self):
        """PostgreSQL DDL must not contain SQLite AUTOINCREMENT keyword."""
        for name, ddl in POSTGRES_DDL:
            self.assertNotIn("AUTOINCREMENT", ddl.upper(), msg=f"Table: {name}")

    def test_06_price_column_is_numeric_not_text(self):
        """Products.price must be NUMERIC(10, 2)."""
        products_ddl = next(ddl for name, ddl in POSTGRES_DDL if name == "products")
        self.assertIn("NUMERIC", products_ddl.upper())

    def test_07_datetime_columns_map_to_timestamp(self):
        """DATETIME columns in Employees and Orders must map to TIMESTAMP."""
        employees_ddl = next(ddl for name, ddl in POSTGRES_DDL if name == "employees")
        orders_ddl    = next(ddl for name, ddl in POSTGRES_DDL if name == "orders")
        self.assertIn("TIMESTAMP", employees_ddl.upper())
        self.assertIn("TIMESTAMP", orders_ddl.upper())

    def test_08_all_eight_tables_in_sqlite_to_pg_map(self):
        """SQLITE_TO_PG must map all 8 SQLite table names."""
        self.assertEqual(len(SQLITE_TO_PG), 8)
        expected_sqlite_names = {
            "Categories", "Customers", "Employees", "Shippers",
            "Suppliers", "Products", "Orders", "OrderDetails",
        }
        self.assertEqual(set(SQLITE_TO_PG.keys()), expected_sqlite_names)

    def test_09_expected_counts_total_932(self):
        """Expected total row count must be 932."""
        self.assertEqual(sum(EXPECTED_COUNTS.values()), 932)
        self.assertEqual(TOTAL_EXPECTED, 932)

    def test_10_build_insert_sql_correct_format(self):
        """build_insert_sql must produce valid parameterised INSERT."""
        sql = build_insert_sql("customers", ["customerid", "customername", "country"])
        self.assertIn("INSERT INTO customers", sql)
        self.assertIn("customerid, customername, country", sql)
        self.assertEqual(sql.count("%s"), 3)

    def test_11_dry_run_prints_ddl_without_connecting(self):
        """--dry-run must print DDL and never call psycopg2.connect."""
        with patch("scripts.migrate_to_postgres.load_env_file"):
            with patch("psycopg2.connect") as mock_connect:
                captured = StringIO()
                with patch("sys.stdout", captured):
                    run_migration(dry_run=True)
                mock_connect.assert_not_called()
                output = captured.getvalue()
                self.assertIn("DRY RUN", output)
                self.assertIn("CREATE TABLE", output)


